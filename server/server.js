require('dotenv').config();
const express=require('express'),http=require('http'),cors=require('cors'),jwt=require('jsonwebtoken'),path=require('path');
const {Server}=require('socket.io');
const {PrismaClient}=require('@prisma/client');
const prisma=require('./prisma'),auth=require('./middleware/auth');
const app=express(),server=http.createServer(app);
// Render sits behind a trusted proxy; use the client IP for login throttling.
app.set('trust proxy',1);
const origins=(process.env.CLIENT_URL||'').split(',').map(x=>x.trim()).filter(Boolean);
const allowedOrigins=[...origins,'capacitor://localhost','http://localhost','https://localhost'];
const isAllowedOrigin=origin=>!origin||allowedOrigins.includes('*')||allowedOrigins.includes(origin)||/^https:\/\/[a-z0-9-]+(?:-[a-z0-9-]+)*\.vercel\.app$/i.test(origin);
const corsOrigin=(origin,callback)=>callback(null,isAllowedOrigin(origin));
app.use(cors({origin:corsOrigin,credentials:false}));
app.use(express.json({limit:'12mb'}));
const io=new Server(server,{cors:{origin:corsOrigin,methods:['GET','POST','PUT']}});
app.set('io',io);
io.use((socket,next)=>{try{const token=socket.handshake.auth?.token;if(!token)throw Error();socket.user=jwt.verify(token,process.env.JWT_SECRET);next();}catch{next(new Error('Unauthorized'));}});
io.on('connection',socket=>{socket.join(socket.user.id);socket.on('call:signal',data=>{if(data?.to&&data?.signal)io.to(data.to).emit('call:signal',{from:socket.user.id,signal:data.signal});});socket.on('call:end',data=>{if(data?.to)io.to(data.to).emit('call:end',{from:socket.user.id});});});
app.get('/api/health',(req,res)=>res.json({ok:true}));
app.get('/api',(req,res)=>res.json({name:'Zero Cross API',status:'running'}));
app.use('/api/auth',require('./routes/auth-public'));
app.use('/api/auth',auth,require('./routes/auth'));
app.use('/api/admin',auth,require('./routes/admin'));
app.use('/api/game',auth,require('./routes/game'));
app.use('/api/users',auth,require('./routes/users'));
app.use('/api/chat',auth,require('./routes/chat'));
app.use('/api/calls',auth,require('./routes/calls'));
const webRoot=path.resolve(__dirname,'../client/dist');
const frontendIndex=path.join(webRoot,'index.html');
app.use(express.static(webRoot));
app.get(/^(?!\/api(?:\/|$)).*/, (req,res)=>res.sendFile(frontendIndex,err=>{if(err){console.error('Frontend build missing:',frontendIndex,err.message);res.status(503).type('text').send('Frontend build is missing. Render must build from the repository root using: npm run build');}}));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:'Internal server error.'});});
const cleanupExpiredMessages=async()=>{try{const now=new Date();const cutoff=new Date(now.getTime()-24*60*60*1000);const expired=await prisma.message.findMany({where:{OR:[{expiresAt:{lte:now}},{createdAt:{lte:cutoff}}]},select:{id:true,senderId:true,receiverId:true}});if(expired.length){await prisma.message.deleteMany({where:{id:{in:expired.map(m=>m.id)}}});for(const m of expired){io.to(m.senderId).emit('message:deleted',{id:m.id});io.to(m.receiverId).emit('message:deleted',{id:m.id});}}const expiredStatuses=await prisma.status.deleteMany({where:{expiresAt:{lte:now}}});if(expiredStatuses.count)console.log('Expired statuses deleted:',expiredStatuses.count);}catch(e){console.error('Expiry cleanup failed:',e.message);}};
cleanupExpiredMessages();
const cleanup=setInterval(cleanupExpiredMessages,60000);
const port=process.env.PORT||5000;server.listen(port,()=>console.log('Zero Cross API + Web running on '+port));
process.on('SIGINT',async()=>{clearInterval(cleanup);await prisma.$disconnect();server.close(()=>process.exit(0));});
